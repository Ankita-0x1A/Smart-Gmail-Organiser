import React, { useState } from "react";
import {
  X,
  Mail,
  CheckCircle2,
  ExternalLink,
  RefreshCw,
  AlertCircle,
  HelpCircle,
  ShieldCheck,
  Unlink,
} from "lucide-react";
import "./CategoryModal.css";

export default function ConnectGmailModal({
  isOpen,
  onClose,
  connectedEmail,
  accountId,
  onSaveAccount,
  onDisconnect,
  onSync,
  syncing = false,
  statusMessage = null,
}) {
  const [inputAccountId, setInputAccountId] = useState("");
  const [inputEmail, setInputEmail] = useState("");
  const [jsonPaste, setJsonPaste] = useState("");
  const [error, setError] = useState(null);
  const [startingOAuth, setStartingOAuth] = useState(false);

  if (!isOpen) return null;

  const handleStartOAuth = async () => {
    setStartingOAuth(true);
    setError(null);
    try {
      const token = localStorage.getItem("token");
      if (!token) {
        throw new Error("You must be logged in to connect Gmail.");
      }

      // Request the Google authorization URL generated by the backend
      const response = await fetch("/api/gmail/connect", {
        headers: {
          Authorization: `Bearer ${token}`,
        },
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.message || "Failed to start Google authorization.");
      }

      if (!data.authUrl) {
        throw new Error("Did not receive a valid authorization URL from the server.");
      }

      // Navigate browser to Google's OAuth consent screen as top-level navigation
      window.location.href = data.authUrl;
    } catch (err) {
      setError(err.message || "Failed to initiate Google authorization.");
      setStartingOAuth(false);
    }
  };

  const handleParseCallbackJson = () => {
    setError(null);
    try {
      if (!jsonPaste.trim()) {
        setError("Please paste the callback JSON response.");
        return;
      }
      const data = JSON.parse(jsonPaste);
      const acc = data.savedAccount || data;
      if (!acc || !acc.id) {
        throw new Error(
          "Invalid format. Expected JSON containing savedAccount with an 'id' field."
        );
      }
      onSaveAccount(String(acc.id), acc.googleEmail || acc.email_address || "");
      setJsonPaste("");
    } catch (err) {
      setError(err.message || "Invalid JSON. Please check the response text.");
    }
  };

  const handleManualSave = (e) => {
    e.preventDefault();
    setError(null);

    const trimmedId = inputAccountId.trim();
    if (!trimmedId || !/^\d+$/.test(trimmedId)) {
      setError("Please enter a valid numeric Account ID.");
      return;
    }

    onSaveAccount(trimmedId, inputEmail.trim());
    setInputAccountId("");
    setInputEmail("");
  };

  return (
    <div className="modal-overlay" onClick={onClose} role="dialog" aria-modal="true">
      <div className="modal-card" style={{ maxWidth: "480px" }} onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
            <Mail size={18} color="var(--primary-600)" />
            <h3 className="modal-title">Gmail Account Connection</h3>
          </div>
          <button
            type="button"
            className="modal-close-btn"
            onClick={onClose}
            aria-label="Close"
          >
            <X size={16} />
          </button>
        </div>

        <div className="modal-body">
          {error && <div className="modal-error-box">{error}</div>}

          {accountId ? (
            /* Active Connected Account State */
            <div style={{ display: "flex", flexDirection: "column", gap: "16px" }}>
              <div
                style={{
                  display: "flex",
                  alignItems: "center",
                  gap: "12px",
                  padding: "16px",
                  backgroundColor: "#f0fdf4",
                  border: "1px solid #bbf7d0",
                  borderRadius: "var(--radius-md)",
                }}
              >
                <div
                  style={{
                    width: "36px",
                    height: "36px",
                    borderRadius: "50%",
                    backgroundColor: "#dcfce7",
                    color: "#166534",
                    display: "flex",
                    alignItems: "center",
                    justifyContent: "center",
                    flexShrink: 0,
                  }}
                >
                  <ShieldCheck size={20} />
                </div>
                <div style={{ display: "flex", flexDirection: "column", minWidth: 0 }}>
                  <div style={{ fontWeight: 600, fontSize: "14px", color: "#14532d" }}>
                    Gmail Connected
                  </div>
                  <div style={{ fontSize: "12px", color: "#166534" }}>
                    {connectedEmail ? (
                      <span><strong>{connectedEmail}</strong> (Account ID: {accountId})</span>
                    ) : (
                      <span>Account ID: <strong>{accountId}</strong></span>
                    )}
                  </div>
                </div>
              </div>

              <div style={{ display: "flex", gap: "10px" }}>
                <button
                  type="button"
                  className="modal-btn modal-btn-primary"
                  onClick={onSync}
                  disabled={syncing}
                  style={{ flex: 1, display: "flex", alignItems: "center", justifyContent: "center", gap: "6px" }}
                >
                  <RefreshCw size={14} className={syncing ? "spin-icon" : ""} />
                  <span>{syncing ? "Syncing..." : "Sync Emails Now"}</span>
                </button>

                {onDisconnect && (
                  <button
                    type="button"
                    className="modal-btn modal-btn-cancel"
                    onClick={onDisconnect}
                    title="Disconnect account"
                  >
                    <Unlink size={14} />
                    <span>Disconnect</span>
                  </button>
                )}
              </div>
            </div>
          ) : (
            /* Not Connected State */
            <div style={{ display: "flex", flexDirection: "column", gap: "14px" }}>
              <div
                style={{
                  padding: "12px 14px",
                  backgroundColor: "#fff7ed",
                  border: "1px solid #ffedd5",
                  borderRadius: "var(--radius-md)",
                  display: "flex",
                  gap: "10px",
                }}
              >
                <AlertCircle size={18} color="#c2410c" style={{ flexShrink: 0, marginTop: "2px" }} />
                <div style={{ fontSize: "12px", color: "#9a3412", lineHeight: 1.5 }}>
                  <strong>No Gmail account connected yet.</strong>
                  <br />
                  Authorize your Google account to enable email synchronization and automated AI categorization.
                </div>
              </div>

              {/* Step 1: Authorize with Google */}
              <button
                type="button"
                className="modal-btn modal-btn-primary"
                onClick={handleStartOAuth}
                disabled={startingOAuth}
                style={{
                  display: "flex",
                  alignItems: "center",
                  justifyContent: "center",
                  gap: "8px",
                  padding: "10px",
                  fontSize: "13px",
                }}
              >
                <ExternalLink size={15} />
                <span>{startingOAuth ? "Starting OAuth..." : "1. Authorize with Google OAuth"}</span>
              </button>

              {/* Step 2: Paste Callback or Enter Real Account ID */}
              <div
                style={{
                  fontSize: "11px",
                  color: "var(--text-muted)",
                  lineHeight: 1.4,
                  backgroundColor: "var(--bg-app)",
                  padding: "10px",
                  borderRadius: "var(--radius-sm)",
                  border: "1px solid var(--border-light)",
                }}
              >
                Google authorization saves the account in PostgreSQL and returns the real Account ID.
              </div>

              {/* Option A: Paste callback JSON */}
              <div className="modal-form-group">
                <label className="modal-label">
                  Paste OAuth Callback JSON:
                </label>
                <textarea
                  className="modal-input"
                  style={{ height: "60px", padding: "8px", resize: "none", fontFamily: "monospace", fontSize: "11px" }}
                  placeholder='{"message":"...","savedAccount":{"id":"1","googleEmail":"..."}}'
                  value={jsonPaste}
                  onChange={(e) => setJsonPaste(e.target.value)}
                />
                {jsonPaste.trim() && (
                  <button
                    type="button"
                    className="modal-btn modal-btn-primary"
                    style={{ marginTop: "4px", padding: "6px 12px", fontSize: "12px", alignSelf: "flex-start" }}
                    onClick={handleParseCallbackJson}
                  >
                    Import Account from JSON
                  </button>
                )}
              </div>

              <div
                style={{
                  display: "flex",
                  alignItems: "center",
                  gap: "10px",
                  color: "var(--text-dim)",
                  fontSize: "10px",
                  fontWeight: 600,
                  textTransform: "uppercase",
                }}
              >
                <div style={{ flex: 1, height: "1px", backgroundColor: "var(--border-light)" }} />
                <span>Or Enter Real Account ID Directly</span>
                <div style={{ flex: 1, height: "1px", backgroundColor: "var(--border-light)" }} />
              </div>

              {/* Option B: Enter Real Account ID */}
              <form onSubmit={handleManualSave} style={{ display: "flex", flexDirection: "column", gap: "10px" }}>
                <div style={{ display: "flex", gap: "8px" }}>
                  <div style={{ width: "110px" }}>
                    <input
                      type="text"
                      className="modal-input"
                      placeholder="Account ID (e.g. 1)"
                      value={inputAccountId}
                      onChange={(e) => setInputAccountId(e.target.value)}
                      required
                    />
                  </div>
                  <div style={{ flex: 1 }}>
                    <input
                      type="email"
                      className="modal-input"
                      placeholder="Email (e.g. ishanir908@gmail.com)"
                      value={inputEmail}
                      onChange={(e) => setInputEmail(e.target.value)}
                    />
                  </div>
                </div>

                <button
                  type="submit"
                  className="modal-btn"
                  style={{
                    backgroundColor: "var(--bg-surface-subtle)",
                    color: "var(--text-main)",
                    border: "1px solid var(--border-neutral)",
                    padding: "7px 14px",
                    fontSize: "12px",
                  }}
                  disabled={!inputAccountId.trim()}
                >
                  Save Active Account ID
                </button>
              </form>
            </div>
          )}

          {statusMessage && (
            <div
              style={{
                marginTop: "12px",
                padding: "8px 12px",
                borderRadius: "var(--radius-sm)",
                backgroundColor: "var(--primary-50)",
                border: "1px solid var(--primary-200)",
                color: "var(--primary-700)",
                fontSize: "12px",
              }}
            >
              {statusMessage}
            </div>
          )}
        </div>

        <div className="modal-footer">
          <button
            type="button"
            className="modal-btn modal-btn-cancel"
            onClick={onClose}
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
}
